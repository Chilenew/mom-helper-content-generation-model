"""Summarise runs.jsonl per stage and model, and write the table into COSTS.md between markers.

Usage: python pipeline/costs_report.py

List-price equivalents use the rates in PRICES below. They are what the same work would cost on a paid
tier; update them from the providers' pricing pages when you check, and say when you checked in COSTS.md.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, RUNS_LOG  # noqa: E402

BEGIN, END = "<!-- COSTS:BEGIN (generated by pipeline/costs_report.py) -->", "<!-- COSTS:END -->"

# USD list prices used for the "if we paid" column. Assumptions: verify and date them in COSTS.md.
PRICES = {
    # Cloudflare Workers AI, FLUX.2 [klein] 4B: $0.000287 per output 512x512 tile; a 1024x1024 image = 4 tiles
    "per_image_flux2_klein_1024": 4 * 0.000287,
    # Cloud GPU list price for one NVIDIA T4, per hour (assumption; check a cloud provider's current price)
    "t4_gpu_hour": 0.35,
}


def list_price(rec):
    model = (rec.get("model") or "").lower()
    if rec.get("status") != "ok":
        return 0.0
    if "flux-2-klein" in model:
        p = rec.get("params") or {}
        tiles = max(1, round((p.get("w", 1024) * p.get("h", 1024)) / (512 * 512)))
        return tiles * 0.000287
    if rec.get("gpu_minutes"):
        return rec["gpu_minutes"] / 60 * PRICES["t4_gpu_hour"]
    return 0.0


def main():
    if not RUNS_LOG.exists() or not RUNS_LOG.read_text().strip():
        sys.exit("runs.jsonl is empty: run some stages first")
    rows = defaultdict(lambda: {"calls": 0, "ok": 0, "errors": 0, "latency": [], "gpu_min": 0.0,
                                "cost": 0.0, "list": 0.0})
    for line in RUNS_LOG.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        k = (r.get("stage"), r.get("model"))
        row = rows[k]
        row["calls"] += 1
        row["ok" if r.get("status") == "ok" else "errors"] += 1
        if r.get("status") == "ok":
            row["latency"].append(r.get("latency_s") or 0)
        row["gpu_min"] += r.get("gpu_minutes") or 0
        row["cost"] += r.get("cost_usd") or 0
        row["list"] += list_price(r)

    lines = ["| Stage | Model | Calls | OK | Errors | Mean latency (s) | Total latency (s) | GPU min | Paid (USD) | List-price equiv. (USD) |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    tot = defaultdict(float)
    for (stage, model), r in sorted(rows.items(), key=lambda x: (x[0][0] or "", x[0][1] or "")):
        lat = r["latency"]
        mean = sum(lat) / len(lat) if lat else 0
        lines.append(f"| {stage} | `{model}` | {r['calls']} | {r['ok']} | {r['errors']} | {mean:.1f} | "
                     f"{sum(lat):.1f} | {r['gpu_min']:.1f} | {r['cost']:.2f} | {r['list']:.3f} |")
        for key, val in (("calls", r["calls"]), ("lat", sum(lat)), ("gpu", r["gpu_min"]), ("cost", r["cost"]),
                         ("list", r["list"])):
            tot[key] += val
    lines.append(f"| **Total** | | {int(tot['calls'])} | | | | {tot['lat']:.1f} | {tot['gpu']:.1f} | "
                 f"{tot['cost']:.2f} | {tot['list']:.3f} |")
    table = "\n".join(lines)

    costs = ROOT / "COSTS.md"
    text = costs.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        post = rest.split(END, 1)[1]
        text = f"{pre}{BEGIN}\n{table}\n{END}{post}"
    else:
        text += f"\n{BEGIN}\n{table}\n{END}\n"
    costs.write_text(text, encoding="utf-8")
    print(table)
    print("\nCOSTS.md updated.")


if __name__ == "__main__":
    main()
