"""The whole film, one command. Runs each stage in order; every stage is cached, so re-runs only redo what changed.

  python src/pipeline.py film               validate -> prompts -> narration -> images -> video -> music -> assemble
                                           (Amharic voice + English subs, all-Amharic *_am.mp4, English voice-over *_en.mp4)
  python src/pipeline.py film --dry-run     the same with placeholder narration and frames: no API keys needed
  python src/pipeline.py regen s05          regenerate one shot's narration + image, then re-assemble
  python src/pipeline.py radio [--dry-run]  narration + radio cut (Phase 1 checkpoint)

  python src/pipeline.py validate           check storyboard/storyboard.json against the schema
  python src/pipeline.py prompts            write prompts/*.md from the storyboard, for review
  python src/pipeline.py smoke              call each hosted provider once, log latency to logs/runs.jsonl
  python src/pipeline.py costs              summarise logs/runs.jsonl into COSTS.md
  python src/pipeline.py script draft|translate ...   Gemini storyboard drafts and translations

Each stage can also be run on its own: src/generate_audio.py, src/generate_images.py,
src/generate_video.py, src/assemble_film.py.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import PROMPTS_DIR, ROOT, RUNS_LOG, SRC, STORYBOARD, load_storyboard, rel  # noqa: E402

PASSTHROUGH = {"smoke": "smoke_test.py", "costs": "costs_report.py", "script": "script.py"}
GENERATED_NOTE = ("<!-- Generated by `python src/pipeline.py prompts` from storyboard/storyboard.json. "
                  "Edit the storyboard, not this file. -->\n\n")


def run(script, *args):
    """Run one stage as its own process, exactly as you would by hand; stop the pipeline if it fails."""
    cmd = [sys.executable, str(SRC / script), *map(str, args)]
    print(f"\n$ python {rel(SRC / script)} {' '.join(map(str, args))}".rstrip())
    sys.stdout.flush()  # keep our "$ python ..." line ahead of the child's output
    result = subprocess.run(cmd, cwd=ROOT)
    if result.returncode != 0:
        sys.exit(result.returncode)


# ---------------------------------------------------------------- prompts/*.md

def write_prompts(sb):
    """Human-readable copies of every prompt the models receive, regenerated from the storyboard."""
    from generate_images import character_block, model_settings, reference_characters, reference_prompt, shot_prompt

    PROMPTS_DIR.mkdir(parents=True, exist_ok=True)
    model = model_settings(sb)[0]

    lines = [f"# Character references\n\n{GENERATED_NOTE}",
             f"Model: `{model}`. Each character gets reference-sheet candidates "
             "(`python src/generate_images.py refs`); one is approved as the golden reference and conditions "
             "every keyframe the character appears in.\n"]
    for c in sb["characters"]:
        lines += [f"\n## {c['name']} (`{c['id']}`)\n",
                  f"- Seed: {c['seed']}",
                  f"- Shows face: {'yes' if c.get('show_face', True) else 'no'}",
                  f"- Approved reference: {c.get('reference_image') or 'not yet approved'}\n",
                  f"**Description used in every shot prompt**\n\n> {c['description']}\n",
                  f"**Reference-sheet prompt**\n\n```text\n{reference_prompt(sb, c)}\n```"]
    (PROMPTS_DIR / "character_reference.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = [f"# Image prompts\n\n{GENERATED_NOTE}",
             f"Model: `{model}`. One keyframe per shot, written to `assets/images/<shot>.png`.\n",
             f"**Style block**\n\n> {sb['style_block']}\n",
             f"**Negative prompt**\n\n> {sb['negative_prompt']}\n"]
    for shot in sb["shots"]:
        cast = character_block(sb, shot["characters"]) if shot["characters"] else "none"
        lines += [f"\n## {shot['id']} ({shot['shot_size']}, {shot['duration_s']}s)\n",
                  f"- Seed: {shot['keyframe']['seed']}",
                  f"- Characters: {', '.join(shot['characters']) or 'none'}",
                  f"- Why this shot: {shot['reason']}\n",
                  f"**Full prompt sent to the model**\n\n```text\n"
                  f"{shot_prompt(sb, shot, reference_characters(sb, shot, model))}\n```",
                  f"\n<details><summary>Cast block</summary>\n\n{cast}\n\n</details>"]
    (PROMPTS_DIR / "image_prompts.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    m = sb["models"]["shots"]
    lines = [f"# Motion prompts\n\n{GENERATED_NOTE}",
             f"Model: `{m['name']}` on `{m['provider']}`. Shots with mode `i2v` are animated from their keyframe; "
             "the others (and any i2v shot without a clip) get a Ken Burns move over the keyframe.\n",
             f"Params: `{json.dumps(m.get('params', {}))}`\n",
             "| Shot | Mode | Seed | Duration | Prompt |", "|---|---|---|---|---|"]
    for shot in sb["shots"]:
        mo = shot["motion"]
        prompt = mo.get("prompt", "").replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {shot['id']} | {mo['mode']} | {mo.get('seed', '')} | {shot['duration_s']}s | {prompt} |")
    (PROMPTS_DIR / "motion_prompts.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"prompts: wrote {', '.join(rel(p) for p in sorted(PROMPTS_DIR.glob('*.md')))}", flush=True)


# ---------------------------------------------------------------- commands

def cmd_validate(args):
    run("validate.py", rel(STORYBOARD))


def cmd_prompts(args):
    write_prompts(load_storyboard())


def cmd_film(args):
    dry = ["--dry-run"] if args.dry_run else []
    cmd_validate(args)
    cmd_prompts(args)
    run("generate_audio.py", "narration", *dry)
    run("generate_images.py", "shots", *dry)
    run("generate_video.py", "render")
    run("generate_audio.py", "music", "build")
    run("assemble_film.py")
    run("assemble_film.py", "--subtitles", "am")
    run("generate_audio.py", "narration-en", *dry)
    run("assemble_film.py", "--narration", "en")


def cmd_radio(args):
    cmd_validate(args)
    run("generate_audio.py", "narration", *(["--dry-run"] if args.dry_run else []))
    run("generate_audio.py", "radio")


def cmd_regen(args):
    cmd_validate(args)
    run("generate_audio.py", "narration", "--only", args.shot)
    run("generate_images.py", "shots", "--only", args.shot)
    run("generate_video.py", "render")
    run("generate_audio.py", "music", "build")
    run("assemble_film.py")
    if RUNS_LOG.exists():
        print("--- model calls logged in this run:")
        print("\n".join(RUNS_LOG.read_text(encoding="utf-8").splitlines()[-5:]))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("film", help="build the whole film")
    f.add_argument("--dry-run", action="store_true", help="placeholder narration and frames, no API keys")
    f.set_defaults(fn=cmd_film)
    r = sub.add_parser("radio", help="narration + radio cut")
    r.add_argument("--dry-run", action="store_true")
    r.set_defaults(fn=cmd_radio)
    g = sub.add_parser("regen", help="regenerate one shot, then re-assemble")
    g.add_argument("shot")
    g.set_defaults(fn=cmd_regen)
    sub.add_parser("validate").set_defaults(fn=cmd_validate)
    sub.add_parser("prompts").set_defaults(fn=cmd_prompts)
    # Thin pass-throughs to the helper scripts, so there is one front door. Their arguments (including
    # --help) go straight to the helper, so they are routed before argparse sees them.
    for name, script in PASSTHROUGH.items():
        sub.add_parser(name, help=f"runs src/{script} with the remaining arguments")
    if len(sys.argv) > 1 and sys.argv[1] in PASSTHROUGH:
        run(PASSTHROUGH[sys.argv[1]], *sys.argv[2:])
        return
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
